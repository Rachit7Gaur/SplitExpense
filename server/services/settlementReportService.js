
const PDFDocument = require('pdfkit');

const GREEN = '#10251f';
const TEAL = '#07866d';
const LIGHT = '#f1f7f4';
const MUTED = '#64748b';
const ORANGE = '#e76f51';

const PAGE_WIDTH = 595.28;
const FOOTER_Y = 805;
const TABLE_BOTTOM = 775;
const ROW_HEIGHT = 27;

// Approximate space needed for the analytics chart and highlight cards.
const ANALYTICS_REQUIRED_SPACE = 280;

function formatMoney(amountInPaise) {
  return `Rs. ${(amountInPaise / 100).toLocaleString('en-IN', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}

function formatDate(date) {
  return new Date(date).toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });
}

function drawHeader(doc, title, subtitle) {
  doc.rect(0, 0, PAGE_WIDTH, 112).fill(GREEN);

  doc.fillColor('#ffffff')
    .font('Helvetica-Bold')
    .fontSize(19)
    .text('EquiSplit', 36, 27);

  doc.fontSize(9)
    .font('Helvetica')
    .fillColor('#b7d5ca')
    .text('TRIP SETTLEMENT REPORT', 36, 55);

  doc.font('Helvetica-Bold')
    .fontSize(23)
    .fillColor('#ffffff')
    .text(title, 36, 72, { width: 520 });

  if (subtitle) {
    doc.font('Helvetica')
      .fontSize(9)
      .fillColor('#d3e5df')
      .text(subtitle, 36, 98, { width: 520 });
  }
}

function drawContinuationHeader(doc, title, subtitle) {
  doc.rect(0, 0, PAGE_WIDTH, 42).fill(GREEN);

  doc.font('Helvetica-Bold')
    .fontSize(12)
    .fillColor('#ffffff')
    .text(`EquiSplit · ${title}`, 36, 15);

  doc.font('Helvetica')
    .fontSize(8)
    .fillColor('#d3e5df')
    .text(subtitle || '', 390, 17, {
      width: 169,
      align: 'right',
    });
}

function drawSectionTitle(doc, title, x, y) {
  doc.font('Helvetica-Bold')
    .fontSize(12)
    .fillColor(GREEN)
    .text(title, x, y);
}

function drawFooter(doc, pageNumber, totalPages) {
  const y = FOOTER_Y;

  doc.moveTo(36, y)
    .lineTo(559, y)
    .strokeColor('#e5ece8')
    .stroke();

  doc.font('Helvetica')
    .fontSize(8)
    .fillColor(MUTED)
    .text(
      `Generated by EquiSplit · ${formatDate(new Date())}`,
      36,
      y + 10
    );

  doc.text(`Page ${pageNumber} of ${totalPages}`, 470, y + 10, {
    width: 89,
    align: 'right',
  });
}

function drawSummaryCard(doc, x, y, width, label, value) {
  doc.roundedRect(x, y, width, 57, 8).fill(LIGHT);

  doc.font('Helvetica')
    .fontSize(8)
    .fillColor(MUTED)
    .text(label, x + 10, y + 10);

  doc.font('Helvetica-Bold')
    .fontSize(14)
    .fillColor(GREEN)
    .text(value, x + 10, y + 27, {
      width: width - 20,
      ellipsis: true,
    });
}


function drawContributionBars(doc, balances, expenses, startY) {
  drawSectionTitle(doc, 'Who contributed', 36, startY);

  const total = expenses.reduce(
    (sum, expense) => sum + expense.amount,
    0
  );

  const payerTotals = new Map();

  expenses.forEach((expense) => {
    const contributions = expense.contributions?.length
      ? expense.contributions
      : expense.paidBy
        ? [{ user: expense.paidBy, amount: expense.amount }]
        : [];

    contributions.forEach((contribution) => {
      const userId = contribution.user?._id?.toString()
        || contribution.user?.toString();

      if (!userId) return;

      payerTotals.set(
        userId,
        (payerTotals.get(userId) || 0) + contribution.amount
      );
    });
  });

  const colors = [TEAL, '#4263cc', ORANGE, '#d99b13', '#8b5cf6'];

  let y = startY + 25;

  balances.forEach((member, index) => {
    const paid = payerTotals.get(member.userId.toString()) || 0;
    const percentage = total > 0 ? (paid / total) * 100 : 0;

    doc.font('Helvetica')
      .fontSize(8)
      .fillColor(GREEN)
      .text(member.name, 36, y);

    doc.font('Helvetica-Bold')
      .text(formatMoney(paid), 450, y, {
        width: 109,
        align: 'right',
      });

    doc.roundedRect(36, y + 13, 523, 7, 3).fill('#e8efeb');

    if (percentage > 0) {
      doc.roundedRect(
        36,
        y + 13,
        Math.max(7, 523 * percentage / 100),
        7,
        3
      ).fill(colors[index % colors.length]);
    }

    y += 34;
  });
}


function drawSettlements(doc, settlements, startY) {
  drawSectionTitle(doc, 'Final settlement', 36, startY);

  let y = startY + 23;

  if (settlements.length === 0) {
    doc.roundedRect(36, y, 523, 31, 7).fill(LIGHT);

    doc.font('Helvetica')
      .fontSize(9)
      .fillColor(TEAL)
      .text('Everyone is settled up!', 48, y + 10);

    return y + 40;
  }

  settlements.forEach((settlement) => {
    doc.roundedRect(36, y, 523, 29, 6).fill(LIGHT);

    doc.font('Helvetica')
      .fontSize(8)
      .fillColor(GREEN)
      .text(
        `${settlement.from.name} pays ${settlement.to.name}`,
        48,
        y + 10,
        { width: 340 }
      );

    doc.font('Helvetica-Bold')
      .fillColor(TEAL)
      .text(formatMoney(settlement.amount), 420, y + 10, {
        width: 127,
        align: 'right',
      });

    y += 35;
  });

  return y;
}


function drawDailyChart(doc, expenses, startY) {
  drawSectionTitle(doc, 'Daily spending trend', 36, startY);

  doc.font('Helvetica')
    .fontSize(8)
    .fillColor(MUTED)
    .text('Total expenses recorded on each date (INR)', 36, startY + 17);

  const dailyTotals = new Map();

  expenses.forEach((expense) => {
    const date = new Date(expense.createdAt);

    const key = [
      date.getFullYear(),
      String(date.getMonth() + 1).padStart(2, '0'),
      String(date.getDate()).padStart(2, '0'),
    ].join('-');

    dailyTotals.set(
      key,
      (dailyTotals.get(key) || 0) + expense.amount
    );
  });

  const days = Array.from(dailyTotals.entries())
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([date, total]) => ({ date, total }));

  if (days.length === 0) {
    doc.font('Helvetica')
      .fontSize(9)
      .fillColor(MUTED)
      .text('No spending data available.', 36, startY + 45);

    return;
  }

  // Chart dimensions.
  const chartX = 90;
  const chartY = startY + 55;
  const chartWidth = 440;
  const chartHeight = 115;

  const max = Math.max(...days.map((day) => day.total), 1);
  const axisMax = Math.ceil(max / 100000) * 100000 || 100000;

  // Format axis values from paise to rupees.
  function formatAxisMoney(value) {
    return `Rs. ${Math.round(value / 100).toLocaleString('en-IN')}`;
  }

  // Draw Y-axis labels and horizontal grid lines.
  [0, 0.25, 0.5, 0.75, 1].forEach((ratio) => {
    const y = chartY + chartHeight * (1 - ratio);
    const value = axisMax * ratio;

    doc.moveTo(chartX, y)
      .lineTo(chartX + chartWidth, y)
      .strokeColor('#e5ece8')
      .lineWidth(0.7)
      .stroke();

    doc.font('Helvetica')
      .fontSize(7)
      .fillColor(MUTED)
      .text(formatAxisMoney(value), 30, y - 4, {
        width: 52,
        align: 'right',
      });
  });

  // Calculate the position of every daily spending point.
  const points = days.map((day, index) => ({
    x: days.length === 1
      ? chartX + chartWidth / 2
      : chartX + (index / (days.length - 1)) * chartWidth,

    y: chartY + chartHeight -
      (day.total / axisMax) * chartHeight,
  }));

  // Draw the line connecting the daily totals.
  if (points.length > 1) {
    doc.moveTo(points[0].x, points[0].y);

    points.slice(1).forEach((point) => {
      doc.lineTo(point.x, point.y);
    });

    doc.strokeColor(TEAL)
      .lineWidth(2)
      .stroke();
  }

  // Draw points and their values.
  points.forEach((point, index) => {
    doc.circle(point.x, point.y, 3.5).fill(TEAL);

    // Show every value for short charts; otherwise show selected values.
    const showValue =
      days.length <= 6 ||
      index === 0 ||
      index === points.length - 1;

    if (showValue) {
      doc.font('Helvetica-Bold')
        .fontSize(7)
        .fillColor(GREEN)
        .text(
          formatMoney(days[index].total),
          point.x - 35,
          point.y - 15,
          {
            width: 70,
            align: 'center',
          }
        );
    }
  });

  // Display date labels.
  days.forEach((day, index) => {
    const showDate =
      days.length <= 6 ||
      index === 0 ||
      index === points.length - 1 ||
      index % Math.ceil(days.length / 5) === 0;

    if (showDate) {
      doc.font('Helvetica')
        .fontSize(7)
        .fillColor(MUTED)
        .text(
          formatDate(`${day.date}T00:00:00`),
          points[index].x - 30,
          chartY + chartHeight + 9,
          {
            width: 60,
            align: 'center',
          }
        );
    }
  });

  doc.lineWidth(1);
}


function drawHighlights(doc, expenses, balances, startY) {
  const biggestExpense = expenses.reduce(
    (biggest, expense) =>
      expense.amount > (biggest?.amount || 0) ? expense : biggest,
    null
  );

  const topPayer = balances.reduce(
    (top, member) =>
      member.totalPaid > (top?.totalPaid || 0) ? member : top,
    null
  );

  const dailyTotals = new Map();

  expenses.forEach((expense) => {
    const date = new Date(expense.createdAt);
    const key = date.toISOString().slice(0, 10);

    dailyTotals.set(
      key,
      (dailyTotals.get(key) || 0) + expense.amount
    );
  });

  const busiestDay = Array.from(dailyTotals.entries()).reduce(
    (best, current) =>
      current[1] > (best?.[1] || 0) ? current : best,
    null
  );

  const cards = [
    {
      title: 'Biggest expense',
      value: biggestExpense?.description || 'No expenses',
      amount: biggestExpense
        ? formatMoney(biggestExpense.amount)
        : 'Rs. 0.00',
    },
    {
      title: 'Busiest day',
      value: busiestDay
        ? formatDate(`${busiestDay[0]}T00:00:00`)
        : 'No activity',
      amount: busiestDay
        ? formatMoney(busiestDay[1])
        : 'Rs. 0.00',
    },
    {
      title: 'Top payer',
      value: topPayer?.name || 'No payer',
      amount: topPayer
        ? formatMoney(topPayer.totalPaid)
        : 'Rs. 0.00',
    },
  ];

  const cardWidth = 163;

  cards.forEach((card, index) => {
    const x = 36 + index * 180;

    doc.roundedRect(x, startY, cardWidth, 66, 8).fill(LIGHT);

    doc.font('Helvetica')
      .fontSize(8)
      .fillColor(MUTED)
      .text(card.title, x + 10, startY + 9);

    doc.font('Helvetica-Bold')
      .fontSize(10)
      .fillColor(GREEN)
      .text(card.value, x + 10, startY + 25, {
        width: cardWidth - 20,
        ellipsis: true,
      });

    doc.font('Helvetica-Bold')
      .fontSize(8)
      .fillColor(TEAL)
      .text(card.amount, x + 10, startY + 45);
  });
}

function drawExpenseTableHeader(doc, startY, continued = false) {
  drawSectionTitle(
    doc,
    continued ? 'Expense details (continued)' : 'Expense details',
    36,
    startY
  );

  const headerY = startY + 25;

  doc.font('Helvetica-Bold')
    .fontSize(8)
    .fillColor(MUTED);

  doc.text('Date', 36, headerY);
  doc.text('Item', 105, headerY);
  doc.text('Contributors', 360, headerY);

  doc.text('Amount', 470, headerY, {
    width: 89,
    align: 'right',
  });

  doc.moveTo(36, headerY + 16)
    .lineTo(559, headerY + 16)
    .strokeColor('#dce7e1')
    .stroke();

  return headerY + 25;
}


function drawExpenseRow(doc, expense, y) {
  doc.moveTo(36, y - 6)
    .lineTo(559, y - 6)
    .strokeColor('#e8eeeb')
    .stroke();

  doc.font('Helvetica')
    .fontSize(8)
    .fillColor(GREEN);

  doc.text(formatDate(expense.createdAt), 36, y, {
    width: 62,
  });

  doc.text(expense.description || 'Untitled expense', 105, y, {
    width: 245,
    ellipsis: true,
  });

  const contributions = expense.contributions?.length
    ? expense.contributions
    : expense.paidBy
      ? [{ user: expense.paidBy, amount: expense.amount }]
      : [];

  const contributorText = contributions
    .map((item) => {
      const name = item.user?.name || 'Unknown';
      return `${name}: ${formatMoney(item.amount)}`;
    })
    .join(', ');

  doc.font('Helvetica')
    .fontSize(7)
    .text(contributorText || 'Unknown', 360, y, {
      width: 100,
      ellipsis: true,
    });

  doc.font('Helvetica-Bold')
    .fontSize(8)
    .text(formatMoney(expense.amount), 470, y, {
      width: 89,
      align: 'right',
    });
}


function drawPaginatedExpenseTable(doc, expenses, startY) {
  let y = drawExpenseTableHeader(doc, startY);

  expenses.forEach((expense) => {
    if (y + ROW_HEIGHT > TABLE_BOTTOM) {
      doc.addPage({
        size: 'A4',
        margin: 0,
      });

      const pageNumber = doc.bufferedPageRange().count;

      drawContinuationHeader(
        doc,
        'Expense History',
        `Continuation · Page ${pageNumber}`
      );

      y = drawExpenseTableHeader(doc, 65, true);
    }

    drawExpenseRow(doc, expense, y);

    y += ROW_HEIGHT;
  });

  return y;
}

function drawAnalytics(doc, expenses, balances, startY, dateRange) {
  // A continuation heading is needed if analytics begins on a new page.
  if (startY === 65) {
    drawContinuationHeader(
      doc,
      'Trip Analytics',
      dateRange
    );
  } else {
    drawSectionTitle(doc, 'Trip Analytics', 36, startY);
  }

  const chartStart = startY + 15;

  drawDailyChart(doc, expenses, chartStart);

  const highlightsStart = chartStart + 190;

  drawHighlights(
    doc,
    expenses,
    balances,
    highlightsStart
  );
}

function generateSettlementReport(doc, group, expenses, financials) {
  const { balances, settlements } = financials;

  const totalSpent = expenses.reduce(
    (sum, expense) => sum + expense.amount,
    0
  );

  const totalShare = balances.reduce(
    (sum, member) => sum + member.totalShare,
    0
  );

  const totalPaid = balances.reduce(
    (sum, member) => sum + member.totalPaid,
    0
  );

  const totalNetBalance = balances.reduce(
    (sum, member) => sum + member.netBalance,
    0
  );

  // Financial consistency check.
  if (
    totalSpent !== totalShare ||
    totalSpent !== totalPaid ||
    totalNetBalance !== 0
  ) {
    throw new Error(
      'Financial data is inconsistent. Report cannot be generated.'
    );
  }

  const averagePerMember = balances.length
    ? totalSpent / balances.length
    : 0;

  const firstExpense = expenses.length
    ? expenses.reduce((first, expense) =>
        new Date(expense.createdAt) < new Date(first.createdAt)
          ? expense
          : first
      )
    : null;

  const lastExpense = expenses.length
    ? expenses.reduce((last, expense) =>
        new Date(expense.createdAt) > new Date(last.createdAt)
          ? expense
          : last
      )
    : null;

  const dateRange = firstExpense && lastExpense
    ? `${formatDate(firstExpense.createdAt)} - ${formatDate(lastExpense.createdAt)}`
    : 'No expenses recorded';

  const subtitle = `${dateRange} · ${balances.length} members`;

  // PAGE 1: Financial overview.
  drawHeader(doc, group.name, subtitle);

  drawSummaryCard(
    doc,
    36,
    132,
    124,
    'TOTAL SPENT',
    formatMoney(totalSpent)
  );

  drawSummaryCard(
    doc,
    171,
    132,
    124,
    'PER PERSON',
    formatMoney(averagePerMember)
  );

  drawSummaryCard(
    doc,
    306,
    132,
    124,
    'EXPENSES',
    String(expenses.length)
  );

  drawSummaryCard(
    doc,
    441,
    132,
    118,
    'MEMBERS',
    String(balances.length)
  );

  drawContributionBars(
    doc,
    balances,
    expenses,
    215
  );

  const settlementEnd = drawSettlements(
    doc,
    settlements,
    215 + balances.length * 34 + 10
  );

  const expenseStart = Math.min(
    settlementEnd + 12,
    650
  );

  // Expense history can continue across multiple pages.
  const expenseEnd = drawPaginatedExpenseTable(
    doc,
    expenses,
    expenseStart
  );

  const analyticsStart = expenseEnd + 20;

console.log('PDF pagination debug:', {
  expenseCount: expenses.length,
  expenseStart,
  expenseEnd,
  analyticsStart,
  availableBottom: FOOTER_Y - 15,
  requiredSpace: ANALYTICS_REQUIRED_SPACE,
  canFitAnalytics:
    analyticsStart + ANALYTICS_REQUIRED_SPACE <= FOOTER_Y - 15,
  currentPage: doc.bufferedPageRange().count,
});

  if (
    analyticsStart + ANALYTICS_REQUIRED_SPACE <= FOOTER_Y - 15
  ) {
    // Analytics fit on the current page.
    drawAnalytics(
      doc,
      expenses,
      balances,
      analyticsStart,
      dateRange
    );
  } else {
    // Not enough room: create a separate analytics page.
    doc.addPage({
      size: 'A4',
      margin: 0,
    });

    drawAnalytics(
      doc,
      expenses,
      balances,
      65,
      dateRange
    );
  }

  // Add footers after all pages have been generated.
  const pageRange = doc.bufferedPageRange();
  const totalPages = pageRange.count;

  for (
    let pageIndex = pageRange.start;
    pageIndex < pageRange.start + pageRange.count;
    pageIndex++
  ) {
    doc.switchToPage(pageIndex);

    drawFooter(
      doc,
      pageIndex + 1,
      totalPages
    );
  }

  // Leave the document positioned on the last page.
  doc.switchToPage(
    pageRange.start + pageRange.count - 1
  );
}

